// Builds js/data/phosphor.js from Phosphor Icons (MIT) bold SVGs.
// Usage: node tools/build-icons.mjs <dir-with-downloaded-svgs>
// Only the path "d" data is kept, so nothing else from the downloaded files ends up in the app.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = process.argv[2];
const MAP = {
  home: 'house', move: 'barbell', leaf: 'leaf', mind: 'brain', moon: 'moon', chart: 'chart-bar', gear: 'sliders-horizontal',
  plus: 'plus', minus: 'minus', check: 'check', x: 'x', left: 'caret-left', right: 'caret-right', play: 'play', pause: 'pause',
  next: 'skip-forward', prev: 'skip-back', drop: 'drop', flame: 'fire', clock: 'clock', video: 'youtube-logo', ext: 'arrow-square-out',
  trash: 'trash', edit: 'pencil-simple', bed: 'bed', heart: 'heart', wind: 'wind', book: 'book-open', scale: 'scales',
  list: 'list-bullets', search: 'magnifying-glass', sparkle: 'sparkle', up: 'caret-up', down: 'caret-down',
  download: 'download-simple', upload: 'upload-simple', volume: 'speaker-high', monitor: 'monitor', phone: 'device-mobile',
};
const out = {};
for (const [key, file] of Object.entries(MAP)) {
  const svg = fs.readFileSync(path.join(SRC, `${file}.svg`), 'utf8');
  const ds = [...svg.matchAll(/\sd="([MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+)"/g)].map((m) => m[1]);
  if (!ds.length) throw new Error('No path data in ' + file);
  out[key] = ds.map((d) => `<path d="${d}"/>`).join('');
}
fs.writeFileSync(path.join(ROOT, 'js/data/phosphor.js'),
  '// GENERATED by tools/build-icons.mjs — Phosphor Icons, bold weight (MIT License, phosphoricons.com). Used in web view.\n' +
  'export const PHOSPHOR = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(`Wrote ${Object.keys(out).length} icons.`);
