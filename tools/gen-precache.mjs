// Generates precache.js (the service worker's file list) with a content hash as the version.
// Run after changing any app file:  node tools/gen-precache.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SHELL_DIRS = ['css', 'js', 'icons'];
const SHELL_FILES = ['index.html', 'manifest.webmanifest'];

async function walk(dir) {
  const out = [];
  for (const e of await fs.readdir(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = path.posix.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(rel)));
    else out.push(rel);
  }
  return out;
}

const shell = [...SHELL_FILES];
for (const d of SHELL_DIRS) shell.push(...(await walk(d)));
const assets = await walk('assets');
const hash = crypto.createHash('sha256');
for (const f of [...shell, 'sw.js'].sort()) hash.update(f).update(await fs.readFile(path.join(ROOT, f)));
const version = hash.digest('hex').slice(0, 10);

const js = `// GENERATED by tools/gen-precache.mjs
self.PRECACHE_VERSION = '${version}';
self.PRECACHE_SHELL = ${JSON.stringify(['./', ...shell.map((f) => './' + f)], null, 0)};
self.PRECACHE_ASSETS = ${JSON.stringify(assets.map((f) => './' + f), null, 0)};
`;
await fs.writeFile(path.join(ROOT, 'precache.js'), js);
console.log(`precache.js: version ${version}, ${shell.length} shell files, ${assets.length} assets`);
